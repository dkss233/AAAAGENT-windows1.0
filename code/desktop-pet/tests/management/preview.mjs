// Isolated browser QA using the actual HTTP server, lifecycle and SQLite store.
import { cp, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fixture } from '../../dist/tests/management/helpers.js';
import { SqliteMemoryStore, CONFIRMED_RETENTION } from '../../dist/memory/sqlite-store.js';
import { SqliteManagementMemoryPort } from '../../dist/memory/management-port.js';
import { confirmedInvitationPolicy } from '../../dist/companion/invitations.js';
import { lifecycle } from '../../dist/tests/memory/lifecycle-fixture.js';
import { seed, scope, NOW } from '../../dist/tests/memory/sqlite-fixture.js';
import { ManagementSettingsStore } from '../../dist/management/settings-store.js';
import { ManagementRuntime } from '../../dist/management/runtime.js';
import { startRuntimeManagement } from '../../dist/management/bootstrap.js';
const project = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
if (!project.includes('/artifacts/worktrees/W0-I-companion-step1-01/')) throw Error('This fixture is restricted to the integration worktree');
const cleanup = [], f = await fixture({ after(fn) { cleanup.push(fn); } });
const ui = join(f.c.projectRoot, 'code/desktop-pet/management/ui');
await cp(join(project, 'management/ui'), ui, { recursive: true });
const index = await readFile(join(ui, 'index.html'), 'utf8');
await writeFile(join(ui, 'index.html'), index.replace('<body>', '<body><p class="notice warning">隔离合成数据库 · 实际管理 API 联调 · 未连接用户记录或模型服务</p>'));
const store = new SqliteMemoryStore({ filename: f.c.database, retention: CONFIRMED_RETENTION, invitations: confirmedInvitationPolicy('Asia/Shanghai'), clock: () => NOW });
seed(store, scope('companion'));
const noCalls = async () => { throw Error('Provider calls disabled in this browser fixture'); };
const memory = new SqliteManagementMemoryPort(store, lifecycle(store, noCalls, noCalls));
const settings = await ManagementSettingsStore.open(join(f.c.projectRoot, 'settings.json'), f.c);
const server = await startRuntimeManagement(f.c, f.configFile, settings, new ManagementRuntime(f.c.sourceRevision), memory);
const receipt = resolve(project, '../../artifacts/W0-I/companion-step1-01/preview-session.json');
await mkdir(dirname(receipt), { recursive: true }); await writeFile(receipt, JSON.stringify({ pid: process.pid, fixtureRoot: f.c.projectRoot, url: server.url }) + '\n', { mode: 0o600 });
process.stdout.write('Isolated actual API browser preview ready; session descriptor saved.\n');
let stopping = false;
const stop = async () => { if (stopping) return; stopping = true; await server.close(); store.close(); for (const fn of cleanup) await fn(); process.exit(0); };
process.once('SIGTERM', stop); process.once('SIGINT', stop); process.stdin.resume(); process.stdin.once('end', stop);
